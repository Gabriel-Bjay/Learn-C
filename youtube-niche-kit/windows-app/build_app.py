#!/usr/bin/env python3
"""Build the Windows app's update manifest and the full WorkRewired.zip.

Run this after changing any file the app ships, then commit the result:

    python windows-app/build_app.py

- windows-app/manifest.txt tells UPDATE.bat (tools/update.ps1) which files to
  fetch from GitHub and what each one's SHA-256 should be.
- WorkRewired.zip is the first-time download, built from the same file list.

"app" files are always replaced when they change. "user" files (anything in a
video folder) are replaced only if the copy on the laptop is one we shipped
before (its hash is in the file's git history); if the user edited it, the new
version is saved next to it as name.NEW.ext instead.
"""

import hashlib
import subprocess
import sys
import zipfile
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
MANIFEST = KIT / "windows-app" / "manifest.txt"
ZIP = KIT / "WorkRewired.zip"

# Libraries the venv needs; update.ps1 reinstalls them whenever this line changes.
PIP = 'kokoro>=0.9.4 soundfile pillow playwright'
BROWSER = "chromium"

# (mode, path in this kit, path inside the WorkRewired folder)
FILES = [
    ("app", "windows-app/SETUP.bat", "SETUP.bat"),
    ("app", "windows-app/MAKE-VIDEO.bat", "MAKE-VIDEO.bat"),
    ("app", "windows-app/UPDATE.bat", "UPDATE.bat"),
    ("app", "windows-app/STUDIO.bat", "STUDIO.bat"),
    ("app", "windows-app/START-HERE.txt", "START-HERE.txt"),
    ("app", "windows-app/tools/setup.ps1", "tools/setup.ps1"),
    ("app", "windows-app/tools/make.ps1", "tools/make.ps1"),
    ("app", "windows-app/tools/update.ps1", "tools/update.ps1"),
    ("app", "windows-app/tools/studio.ps1", "tools/studio.ps1"),
    ("app", "studio.py", "tools/studio.py"),
    ("app", "studio.html", "tools/studio.html"),
    ("app", "voiceover.py", "tools/voiceover.py"),
    ("app", "make_video.py", "tools/make_video.py"),
    ("app", "thumbnail.py", "tools/thumbnail.py"),
    ("app", "PROJECT_INSTRUCTIONS.md", "docs/PROJECT_INSTRUCTIONS.md"),
    ("app", "CHANNEL_SETUP.md", "docs/CHANNEL_SETUP.md"),
    ("app", "VIDEO_IDEAS.md", "docs/VIDEO_IDEAS.md"),
    ("app", "SHOTS.md", "docs/SHOTS.md"),
    ("app", "banner/work-rewired-banner.png", "docs/work-rewired-banner.png"),
    ("user", "videos/01-quibi/quibi_voiceover.txt", "videos/01-quibi/script.txt"),
    ("user", "videos/01-quibi/shots.txt", "videos/01-quibi/shots.txt"),
    ("user", "videos/01-quibi/thumbnail.txt", "videos/01-quibi/thumbnail.txt"),
] + [
    ("user", f"videos/01-quibi/charts/{p.name}", f"videos/01-quibi/charts/{p.name}")
    for p in sorted((KIT / "videos/01-quibi/charts").glob("*.png"))
]

# Only in the first-time zip; the updater never touches these.
ZIP_ONLY = {
    "settings.txt": "VOICE=am_michael\r\n",
    "videos/01-quibi/screenshots/README.txt":
        "Save screenshots here (Win + Shift + S, paste into Paint, save as .png)\r\n"
        "using the exact file names from shots.txt.\r\n",
    "videos/01-quibi/stock/README.txt":
        "Stock clips are downloaded here automatically (Pixabay key).\r\n"
        "Or save clips by hand using the file names the preview run tells you.\r\n",
}


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def git_history_hashes(rel):
    """SHA-256 of every committed version of a kit file (oldest versions included)."""
    path = f"youtube-niche-kit/{rel}"
    commits = subprocess.run(["git", "log", "--format=%H", "--", rel], cwd=KIT,
                             capture_output=True, text=True, check=True).stdout.split()
    hashes = []
    for commit in commits:
        blob = subprocess.run(["git", "show", f"{commit}:{path}"], cwd=KIT, capture_output=True)
        if blob.returncode == 0:
            h = sha256(blob.stdout)
            if h not in hashes:
                hashes.append(h)
    return hashes


def manifest_text():
    lines, entries = [], []
    for mode, src, dest in FILES:
        current = sha256((KIT / src).read_bytes())
        old = [h for h in git_history_hashes(src) if h != current] if mode == "user" else []
        entries.append("\t".join(["FILE", mode, current, src, dest, ",".join(old) or "-"]))
    version = sha256("\n".join(entries + [PIP, BROWSER]).encode())[:12]
    lines = ["# Work Rewired update manifest. Generated by build_app.py - don't edit by hand.",
             f"VERSION\t{version}", f"PIP\t{PIP}", f"BROWSER\t{BROWSER}"] + entries
    return "\n".join(lines) + "\n"


def build_zip(path=ZIP):
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for _, src, dest in FILES:
            z.write(KIT / src, f"WorkRewired/{dest}")
        for dest, text in ZIP_ONLY.items():
            z.writestr(f"WorkRewired/{dest}", text)


def main():
    missing = [src for _, src, _ in FILES if not (KIT / src).is_file()]
    if missing:
        sys.exit("missing: " + ", ".join(missing))
    MANIFEST.write_text(manifest_text(), newline="\n")
    build_zip()
    print(f"wrote {MANIFEST.relative_to(KIT)} and {ZIP.name} ({len(FILES)} files)")


if __name__ == "__main__":
    main()
